def read_json(path):
    return json.loads(Path(path).read_text())


def write_json(path, value, *, overwrite=True):
    path = Path(path)
    if path.exists() and not overwrite:
        raise FileExistsError(f'Refusing to overwrite {path}.')
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + '.tmp')
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False) + '\n')
    temporary.replace(path)


def sha256_file(path):
    with Path(path).open('rb') as artifact:
        return hashlib.file_digest(artifact, 'sha256').hexdigest()


def artifact_files(path):
    """List immutable artifact content, excluding interpreter-generated bytecode caches."""
    path = Path(path)
    return [file for file in sorted(path.rglob('*'))
            if file.is_file() and '__pycache__' not in file.relative_to(path).parts
            and file.suffix != '.pyc']


def sha256_tree(path):
    """Hash relative paths and file hashes for a file or directory tree."""
    path = Path(path)
    if path.is_file():
        return sha256_file(path)
    if not path.is_dir():
        raise FileNotFoundError(path)
    entries = {str(file.relative_to(path)): sha256_file(file) for file in artifact_files(path)}
    if not entries:
        raise ValueError(f'Artifact directory is empty: {path}')
    encoded = json.dumps(entries, sort_keys=True, separators=(',', ':')).encode()
    return hashlib.sha256(encoded).hexdigest()


def tree_files(path):
    path = Path(path)
    if path.is_file():
        return {path.name: sha256_file(path)}
    return {str(file.relative_to(path)): sha256_file(file) for file in artifact_files(path)}


