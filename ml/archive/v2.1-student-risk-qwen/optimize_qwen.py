def cohort_summary(frame, cohort_id, seed=None):
    identifiers = frame.student_id.astype(str).tolist()
    encoded = '\n'.join(identifiers).encode()
    return {'cohort_id': cohort_id, 'seed': seed, 'records': len(frame),
            'unique_students': len(set(identifiers)), 'first_student_id': identifiers[0],
            'last_student_id': identifiers[-1], 'student_ids_sha256': hashlib.sha256(encoded).hexdigest()}


def generate_reserved_cohort(path, count, seed, prefix, *, allow_existing):
    """Create a reserved cohort with globally distinct IDs; never regenerate final data."""
    path = Path(path)
    if path.exists():
        if not allow_existing:
            raise FileExistsError(f'The final cohort already exists: {path}; refusing to regenerate it.')
        frame = load(path)
        if len(frame) != count or not frame.student_id.astype(str).str.startswith(prefix).all():
            raise ValueError(f'Existing cohort does not match its reservation: {path}')
        return frame
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='cohort-', dir=path.parent) as temporary:
        temporary = Path(temporary)
        frame = generate(temporary / 'generated.csv', count=count, seed=seed)
        frame.student_id = frame.student_id.str.replace('DEMO-', prefix, regex=False)
        pending = temporary / 'named.csv'
        frame.to_csv(pending, index=False)
        pending.replace(path)
    return load(path)


def save_scores(path, validation, development, validation_probability, development_probability):
    arrays = {
        'validation_probabilities': np.asarray(validation_probability, dtype=np.float64),
        'development_probabilities': np.asarray(development_probability, dtype=np.float64),
        'validation_labels': validation.at_risk.to_numpy(dtype=np.int64),
        'development_labels': development.at_risk.to_numpy(dtype=np.int64),
        'validation_ids': validation.student_id.to_numpy(dtype=str),
        'development_ids': development.student_id.to_numpy(dtype=str),
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name('scores.tmp.npz')
    np.savez_compressed(temporary, **arrays)
    temporary.replace(path)


def validate_score_npz(path, validation, development):
    """Validate cached score dimensions, IDs, labels, and numeric probability bounds."""
    path = Path(path)
    with np.load(path, allow_pickle=False) as scores:
        required = {f'{partition}_{suffix}' for partition in ('validation', 'development')
                    for suffix in ('probabilities', 'labels', 'ids')}
        if set(scores.files) != required:
            raise ValueError(f'Unexpected score arrays in {path}: {sorted(scores.files)}')
        for partition, frame in (('validation', validation), ('development', development)):
            probabilities = scores[f'{partition}_probabilities']
            labels = scores[f'{partition}_labels']
            identifiers = scores[f'{partition}_ids']
            expected_shape = (len(frame),)
            for array in (probabilities, labels, identifiers):
                if array.shape != expected_shape:
                    raise ValueError(f'{partition} score shape {array.shape} != {expected_shape}.')
            if not np.isfinite(probabilities).all() or ((probabilities < 0) | (probabilities > 1)).any():
                raise ValueError(f'{partition} probabilities are not finite values in [0, 1].')
            if not np.array_equal(labels, frame.at_risk.to_numpy()):
                raise ValueError(f'{partition} labels differ from the source cohort.')
            if not np.array_equal(identifiers.astype(str), frame.student_id.to_numpy(dtype=str)):
                raise ValueError(f'{partition} student IDs differ from the source cohort.')
    return {'validation_probabilities': [len(validation)],
            'development_probabilities': [len(development)]}


def candidate_measurements(validation, development, validation_probability, development_probability):
    selected = recall_operating_point(validation.at_risk, validation_probability)
    fixed = metrics(development.at_risk, development_probability, selected['threshold'])
    return {
        'validation': {'operating_point': selected,
                       'fixed_cutoff': metrics(validation.at_risk, validation_probability,
                                               selected['threshold'])},
        'development': {'fixed_cutoff': fixed,
                        'matched_recall': recall_operating_point(
                            development.at_risk, development_probability),
                        'eligible': development_eligible(fixed)},
    }


def development_eligible(result, target=TARGET_RECALL):
    fixed = result.get('development', result).get('fixed_cutoff', result.get('development', result))
    recall = fixed['recall'] if 'recall' in fixed else fixed['fixed_cutoff']['recall']
    return bool(recall + 1e-12 >= target)


def selection_key(result):
    development = result['development']
    return (development['fixed_cutoff']['precision'],
            development['matched_recall']['precision'],
            development['fixed_cutoff']['pr_auc'])


def select_candidate(results, target=TARGET_RECALL):
    """Apply the preregistered eligibility, lexicographic ordering, and control rule."""
    names = [candidate['name'] for candidate in CANDIDATES]
    by_name = {result['name']: result for result in results}
    if set(by_name) != set(names) or len(results) != len(names):
        raise ValueError('Selection requires exactly the preregistered control and challengers.')
    ordered = [by_name[name] for name in names]
    for result in ordered:
        result['development']['eligible'] = development_eligible(result, target)
    eligible = [result for result in ordered if result['development']['eligible']]
    control = by_name[CONTROL]
    challengers = [result for result in eligible if result['name'] != CONTROL]
    best_challenger = max(challengers, key=selection_key) if challengers else None
    if best_challenger is not None and (not control['development']['eligible']
                                        or selection_key(best_challenger) > selection_key(control)):
        selected = best_challenger
    else:
        selected = control
    return {
        'selected_candidate': selected['name'],
        'selected_challenger': selected['name'] if selected['name'] != CONTROL else None,
        'baseline_retained': selected['name'] == CONTROL,
        'eligible_candidates': [result['name'] for result in eligible],
        'selection_keys': {result['name']: list(selection_key(result)) for result in ordered},
    }


def package_metadata():
    packages = {distribution.metadata['Name']: distribution.version
                for distribution in importlib.metadata.distributions()
                if distribution.metadata['Name']}
    return {'python': platform.python_version(), 'packages': dict(sorted(packages.items()))}


def score_checkpoint(checkpoint, validation, development):
    """Score with the exported float32 runtime, matching baseline GPU comparisons."""
    import torch
    torch.set_num_threads(8)
    runtime = StudentRiskModel(checkpoint, device='cuda:0')
    result = []
    for frame in (validation, development):
        states = [state(row) for _, row in frame.iterrows()]
        result.append(np.asarray(runtime.probabilities(states), dtype=np.float64))
    del runtime
    gc.collect()
    torch.cuda.empty_cache()
    return result


def train_candidate(config, train, validation, output):
    """Train, merge, and recalibrate one challenger using the baseline process."""
    # Unsloth must be imported before transformers.
    from unsloth import FastDecisionModel, DecisionTrainer, is_bfloat16_supported
    import torch
    from transformers import TrainingArguments
    from workflow import decision_rows

    output.mkdir(parents=True, exist_ok=False)
    model, tokenizer = FastDecisionModel.from_pretrained(
        MODEL, revision=EXPECTED_REVISION, max_seq_length=512, load_in_4bit=True,
        local_files_only=True, random_state=SEED)
    model = FastDecisionModel.get_peft_model(
        model, r=config['rank'], lora_alpha=16, lora_dropout=0, random_state=SEED)
    train_items, train_report = FastDecisionModel.build_dataset(decision_rows(train), tokenizer, model)
    validation_items, validation_report = FastDecisionModel.build_dataset(
        decision_rows(validation), tokenizer, model)
    if train_report['skipped'] or validation_report['skipped']:
        raise ValueError('Unsloth skipped input decisions; inspect the dataset before training.')
    trainer = DecisionTrainer(
        model=model, processing_class=tokenizer, train_dataset=train_items,
        eval_dataset=validation_items, args=TrainingArguments(
            output_dir=str(output / 'training'), num_train_epochs=config['epochs'],
            learning_rate=config['learning_rate'], per_device_train_batch_size=8,
            gradient_accumulation_steps=1, warmup_steps=10,
            bf16=is_bfloat16_supported(), fp16=not is_bfloat16_supported(),
            eval_strategy='epoch', save_strategy='no', logging_steps=10,
            report_to='none', seed=SEED))
    torch.cuda.reset_peak_memory_stats()
    started = time.perf_counter()
    training = trainer.train().metrics
    training.update(batch_size=trainer.args.per_device_train_batch_size,
                    gradient_accumulation_steps=trainer.args.gradient_accumulation_steps,
                    effective_batch_size=(trainer.args.per_device_train_batch_size
                                          * trainer.args.gradient_accumulation_steps),
                    peak_allocated_vram_gib=torch.cuda.max_memory_allocated() / 1024**3,
                    wall_seconds=time.perf_counter() - started)
    log_history = trainer.state.log_history
    quantized_calibration = FastDecisionModel.calibrate(model, tokenizer, validation_items)
    model.save_pretrained(str(output / 'adapters'))
    model.save_pretrained_merged(str(output / 'merged'))

    # Recalibrate the merged full-precision deployment weights, not the 4-bit scores.
    del trainer, model
    gc.collect()
    torch.cuda.empty_cache()
    model, tokenizer = FastDecisionModel.from_pretrained(
        str(output / 'merged'), load_in_4bit=False, dtype=torch.bfloat16,
        max_seq_length=512, local_files_only=True)
    validation_items, _ = FastDecisionModel.build_dataset(decision_rows(validation), tokenizer, model)
    merged_calibration = FastDecisionModel.calibrate(model, tokenizer, validation_items)
    model.save_pretrained_merged(str(output / 'merged'))
    sanitize_export_metadata(output)
    del model, tokenizer
    gc.collect()
    torch.cuda.empty_cache()
    return training, log_history, quantized_calibration, merged_calibration


def validate_candidate_manifest(manifest, preregistration):
    """Check required provenance and fixed training conditions without loading a GPU model."""
    required = {'name', 'config', 'model', 'source_dataset_sha256', 'development_dataset_sha256',
                'calibration', 'training', 'artifacts', 'scores_sha256', 'measurements'}
    missing = required - set(manifest)
    if missing:
        raise ValueError(f'Candidate manifest is missing {sorted(missing)}.')
    configs = {candidate['name']: candidate for candidate in preregistration['candidates']}
    if manifest['name'] not in configs or manifest['config'] != configs[manifest['name']]:
        raise ValueError('Candidate configuration is absent from or differs from preregistration.')
    fixed = preregistration['fixed_training']
    training = manifest['training']
    if (training['batch_size'] != fixed['physical_batch_size']
            or training['gradient_accumulation_steps'] != fixed['gradient_accumulation_steps']
            or training['effective_batch_size'] != fixed['effective_batch_size']):
        raise ValueError('Candidate changed the preregistered effective batch conditions.')
    if manifest['model'] != preregistration['model']:
        raise ValueError('Candidate base model or revision differs from preregistration.')
    if manifest['source_dataset_sha256'] != preregistration['source_dataset']['sha256']:
        raise ValueError('Candidate source dataset hash differs from preregistration.')
    if not isinstance(manifest['calibration'].get('merged'), dict):
        raise ValueError('Merged-weight recalibration metadata is required.')
    return True


def completed_candidate(name, preregistration, validation, development):
    manifest_path = manifest_for(name)
    if not manifest_path.exists():
        return None
    manifest = read_json(manifest_path)
    validate_candidate_manifest(manifest, preregistration)
    if manifest['development_dataset_sha256'] != sha256_file(OUTPUT / 'development.csv'):
        raise ValueError(f'{name} used a different development cohort.')
    checkpoint = checkpoint_for(name)
    if sha256_tree(checkpoint) != manifest['artifacts']['merged_tree_sha256']:
        raise ValueError(f'{name} merged checkpoint hash differs from its manifest.')
    if name != CONTROL and sha256_tree(candidate_directory(name) / 'adapters') != manifest['artifacts']['adapters_tree_sha256']:
        raise ValueError(f'{name} adapter hash differs from its manifest.')
    if sha256_file(scores_for(name)) != manifest['scores_sha256']:
        raise ValueError(f'{name} cached scores differ from its manifest.')
    validate_score_npz(scores_for(name), validation, development)
    return manifest


def run_control(preregistration, validation, development):
    completed = completed_candidate(CONTROL, preregistration, validation, development)
    if completed is not None:
        print('CONTROL loaded from validated cache.', flush=True)
        return completed
    directory = candidate_directory(CONTROL)
    directory.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    validation_probability, development_probability = score_checkpoint(
        BASELINE_CHECKPOINT, validation, development)
    save_scores(scores_for(CONTROL), validation, development,
                validation_probability, development_probability)
    config = next(candidate for candidate in CANDIDATES if candidate['name'] == CONTROL)
    baseline = read_json(BASELINE_MANIFEST)
    manifest = {
        'schema_version': 1, 'name': CONTROL, 'config': config,
        'model': preregistration['model'], 'checkpoint': relative_path(BASELINE_CHECKPOINT),
        'source_dataset_sha256': sha256_file(SOURCE),
        'development_dataset_sha256': sha256_file(OUTPUT / 'development.csv'),
        'cohorts': {'validation': cohort_summary(validation, 'original-validation'),
                    'development': cohort_summary(development, 'development', DEVELOPMENT_SEED)},
        'calibration': {'baseline_manifest': baseline['calibration'],
                        'merged': baseline['calibration']},
        'training': {**baseline['training'], 'effective_batch_size': 8,
                     'reused_baseline_artifact': True},
        'artifacts': {'merged_tree_sha256': sha256_tree(BASELINE_CHECKPOINT),
                      'merged_model_sha256': sha256_file(BASELINE_CHECKPOINT / 'model.safetensors')},
        'score_dimensions': validate_score_npz(scores_for(CONTROL), validation, development),
        'scores_sha256': sha256_file(scores_for(CONTROL)),
        'measurements': candidate_measurements(validation, development,
                                               validation_probability, development_probability),
        'scoring_seconds': time.perf_counter() - started,
        'environment': package_metadata(),
    }
    write_json(manifest_for(CONTROL), manifest, overwrite=False)
    print('CONTROL ' + json.dumps(manifest['measurements']), flush=True)
    return manifest


def run_challenger(config, preregistration, train, validation, development):
    completed = completed_candidate(config['name'], preregistration, validation, development)
    if completed is not None:
        print(f"{config['name']} loaded from validated cache.", flush=True)
        return completed
    directory = candidate_directory(config['name'])
    if directory.exists():
        raise FileExistsError(f'Incomplete candidate directory exists: {directory}; inspect it before retrying.')
    started = time.perf_counter()
    training, log_history, quantized_calibration, merged_calibration = train_candidate(
        config, train, validation, directory)
    validation_probability, development_probability = score_checkpoint(
        directory / 'merged', validation, development)
    save_scores(scores_for(config['name']), validation, development,
                validation_probability, development_probability)
    manifest = {
        'schema_version': 1, 'name': config['name'], 'config': config,
        'model': preregistration['model'], 'checkpoint': relative_path(directory / 'merged'),
        'source_dataset_sha256': sha256_file(SOURCE),
        'development_dataset_sha256': sha256_file(OUTPUT / 'development.csv'),
        'cohorts': {'train': cohort_summary(train, 'original-train'),
                    'validation': cohort_summary(validation, 'original-validation'),
                    'development': cohort_summary(development, 'development', DEVELOPMENT_SEED)},
        'calibration': {'quantized_before_merge': quantized_calibration,
                        'merged': merged_calibration},
        'training': training, 'training_log': log_history,
        'artifacts': {
            'merged_tree_sha256': sha256_tree(directory / 'merged'),
            'merged_model_sha256': sha256_file(directory / 'merged/model.safetensors'),
            'adapters_tree_sha256': sha256_tree(directory / 'adapters'),
            'adapter_model_sha256': sha256_file(directory / 'adapters/adapter_model.safetensors'),
        },
        'score_dimensions': validate_score_npz(scores_for(config['name']), validation, development),
        'scores_sha256': sha256_file(scores_for(config['name'])),
        'measurements': candidate_measurements(validation, development,
                                               validation_probability, development_probability),
        'total_seconds': time.perf_counter() - started,
        'environment': package_metadata(),
    }
    write_json(manifest_for(config['name']), manifest, overwrite=False)
    print('CANDIDATE_RESULT ' + json.dumps({'name': config['name'],
          'config': config, 'measurements': manifest['measurements']}), flush=True)
    return manifest


def capture_baseline_integrity():
    """Record active artifact hashes before training so the audit can prove preservation."""
    repository = ROOT.parent.parent
    targets = ['ml/student-risk/outputs/merged', 'ml/student-risk/outputs/adapters',
               'ml/student-risk/outputs/manifest.json', 'ml/student-risk/outputs/predictions.json',
               'ml/student-risk/outputs/cpu-benchmark.json', 'backend/app/data/student-risk-demo.json']
    artifacts = {name: {'sha256': sha256_tree(repository / name),
                        'files': tree_files(repository / name)} for name in targets}
    value = {'artifacts': artifacts}
    path = OUTPUT / 'baseline-integrity.json'
    if path.exists():
        if read_json(path) != value:
            raise ValueError('A protected baseline or LMS artifact changed during optimization.')
    else:
        write_json(path, value, overwrite=False)


def sweep():
    preregistration = prepare_preregistration()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    capture_baseline_integrity()
    train, validation, _ = split(load(SOURCE))
    development = generate_reserved_cohort(
        OUTPUT / 'development.csv', DEVELOPMENT_COUNT, DEVELOPMENT_SEED,
        preregistration['development']['id_prefix'], allow_existing=True)
    manifests = [run_control(preregistration, validation, development)]
    for config in CANDIDATES[1:]:
        manifests.append(run_challenger(config, preregistration, train, validation, development))
    results = [{'name': manifest['name'], 'config': manifest['config'],
                'checkpoint': manifest['checkpoint'],
                'validation': manifest['measurements']['validation'],
                'development': manifest['measurements']['development'],
                'artifacts': manifest['artifacts'],
                'manifest_sha256': sha256_file(manifest_for(manifest['name'])),
                'scores_sha256': manifest['scores_sha256']} for manifest in manifests]
    selection = {'schema_version': 1, 'preregistration_sha256': sha256_file(PREREGISTRATION_PATH),
                 'source_dataset_sha256': sha256_file(SOURCE),
                 'development_dataset_sha256': sha256_file(OUTPUT / 'development.csv'),
                 'development': cohort_summary(development, 'development', DEVELOPMENT_SEED),
                 'candidates': results, **select_candidate(results)}
    write_json(SELECTION_PATH, selection, overwrite=False)
    selected = selection['selected_candidate']
    selected_result = next(result for result in results if result['name'] == selected)
    freeze = {
        'schema_version': 1, 'selected_candidate': selected,
        'selected_challenger': selection['selected_challenger'],
        'baseline_retained': selection['baseline_retained'],
        'validation_cutoff': selected_result['validation']['operating_point']['threshold'],
        'selected_checkpoint': selected_result['checkpoint'],
        'selected_merged_tree_sha256': selected_result['artifacts']['merged_tree_sha256'],
        'selected_merged_model_sha256': selected_result['artifacts']['merged_model_sha256'],
        'selected_scores': relative_path(scores_for(selected)),
        'selected_manifest_sha256': selected_result['manifest_sha256'],
        'preregistration_sha256': selection['preregistration_sha256'],
        'development_selection_sha256': sha256_file(SELECTION_PATH),
        'final': preregistration['final'],
    }
    write_json(FREEZE_PATH, freeze, overwrite=False)
    print('SELECTION ' + json.dumps({key: value for key, value in selection.items()
                                    if key != 'candidates'}), flush=True)
    print('FROZEN ' + json.dumps(freeze), flush=True)
    return selection


def load_freeze():
    preregistration = prepare_preregistration()
    if not FREEZE_PATH.exists() or not SELECTION_PATH.exists():
        raise RuntimeError('Selection and validation cutoff are not frozen; run sweep first.')
    freeze = read_json(FREEZE_PATH)
    if freeze['preregistration_sha256'] != sha256_file(PREREGISTRATION_PATH):
        raise ValueError('Candidate list changed after selection freeze.')
    if freeze['development_selection_sha256'] != sha256_file(SELECTION_PATH):
        raise ValueError('Development selection changed after selection freeze.')
    selection = read_json(SELECTION_PATH)
    if freeze['selected_candidate'] != selection['selected_candidate']:
        raise ValueError('Frozen candidate differs from development selection.')
    if sha256_file(manifest_for(freeze['selected_candidate'])) != freeze['selected_manifest_sha256']:
        raise ValueError('Selected candidate manifest changed after selection freeze.')
    if sha256_tree(ROOT / freeze['selected_checkpoint']) != freeze['selected_merged_tree_sha256']:
        raise ValueError('Selected merged checkpoint changed after selection freeze.')
    if preregistration['final'] != freeze['final']:
        raise ValueError('Final cohort reservation changed after selection freeze.')
    return freeze


def final_evaluation():
    freeze = load_freeze()
    if FINAL_PATH.exists():
        raise FileExistsError('Final evaluation already exists; refusing to add candidates or repeat evaluation.')
    final = generate_reserved_cohort(
        OUTPUT / freeze['final']['file'], freeze['final']['records'], freeze['final']['seed'],
        freeze['final']['id_prefix'], allow_existing=False)
    # Only the original control and frozen selection are loaded for final evaluation.
    names = [CONTROL] if freeze['baseline_retained'] else [CONTROL, freeze['selected_candidate']]
    _, validation, _ = split(load(SOURCE))
    probabilities = {}
    timings = {}
    for name in names:
        started = time.perf_counter()
        # Reuse the validation/dev runtime scorer with a one-row development adapter is undesirable;
        # load the exported runtime directly for final-only scoring.
        import torch
        torch.set_num_threads(8)
        runtime = StudentRiskModel(checkpoint_for(name), device='cuda:0')
        states = [state(row) for _, row in final.iterrows()]
        probabilities[name] = np.asarray(runtime.probabilities(states), dtype=np.float64)
        del runtime
        gc.collect()
        torch.cuda.empty_cache()
        timings[name] = time.perf_counter() - started
    arrays = {}
    results = {}
    for name in names:
        manifest = read_json(manifest_for(name))
        cutoff = manifest['measurements']['validation']['operating_point']['threshold']
        if name == freeze['selected_candidate'] and cutoff != freeze['validation_cutoff']:
            raise ValueError('Selected cutoff differs from the freeze.')
        score = probabilities[name]
        results[name] = {
            'validation_operating_point': manifest['measurements']['validation']['operating_point'],
            'fixed_cutoff': metrics(final.at_risk, score, cutoff),
            'matched_recall': recall_operating_point(final.at_risk, score),
            'merged_tree_sha256': sha256_tree(checkpoint_for(name)),
            'merged_model_sha256': sha256_file(checkpoint_for(name) / 'model.safetensors'),
        }
        arrays[f'{name}_probabilities'] = score
    arrays['final_labels'] = final.at_risk.to_numpy(dtype=np.int64)
    arrays['final_ids'] = final.student_id.to_numpy(dtype=str)
    score_path = OUTPUT / 'final-scores.npz'
    temporary = OUTPUT / 'final-scores.tmp.npz'
    np.savez_compressed(temporary, **arrays)
    temporary.replace(score_path)
    if freeze['baseline_retained']:
        comparison = None
        outcome = 'baseline_retained_no_preferable_challenger'
    else:
        comparison = bootstrap_precision_difference(
            final.at_risk, probabilities[CONTROL], probabilities[freeze['selected_candidate']])
        selected_precision = results[freeze['selected_candidate']]['matched_recall']['precision']
        control_precision = results[CONTROL]['matched_recall']['precision']
        comparison['observed_selected_minus_control'] = selected_precision - control_precision
        low, high = comparison['interval_95']
        outcome = ('established_improvement' if low > 0 else
                   'established_regression' if high < 0 else 'inconclusive_interval_spans_zero')
    selected_result = results[freeze['selected_candidate']]
    report = {
        'schema_version': 1, 'freeze': freeze,
        'preregistration_sha256': freeze['preregistration_sha256'],
        'selection_sha256': freeze['development_selection_sha256'],
        'source_dataset_sha256': sha256_file(SOURCE),
        'development_dataset_sha256': sha256_file(OUTPUT / 'development.csv'),
        'final_dataset_sha256': sha256_file(OUTPUT / freeze['final']['file']),
        'final_cohort': cohort_summary(final, 'final', FINAL_SEED),
        'evaluated_models': names, 'results': results,
        'paired_student_bootstrap_matched_precision': comparison,
        'matched_recall_outcome': outcome,
        'selected_operational_target_met': selected_result['fixed_cutoff']['recall'] >= TARGET_RECALL,
        'final_scores_sha256': sha256_file(score_path),
        'score_dimensions': {key: list(value.shape) for key, value in arrays.items()},
        'cohort_ids': {'final_first': final.student_id.iloc[0],
                       'final_last': final.student_id.iloc[-1],
                       'all_ids_stored_in': 'final-scores.npz:final_ids'},
        'scoring_seconds': timings, 'environment': package_metadata(),
        'synthetic_only': True, 'students_demo_available': False,
        'production_promotion': False, 'aws_deployment': False,
    }
    write_json(FINAL_PATH, report, overwrite=False)
    print('FINAL_RESULT ' + json.dumps(report), flush=True)
    return report


def assert_mapping_close(actual, expected, path=''):
    if isinstance(expected, dict):
        if set(actual) != set(expected):
            raise ValueError(f'{path} keys differ from cached metrics.')
        for key in expected:
            assert_mapping_close(actual[key], expected[key], f'{path}.{key}')
    elif isinstance(expected, list):
        if len(actual) != len(expected):
            raise ValueError(f'{path} lengths differ.')
        for index, value in enumerate(expected):
            assert_mapping_close(actual[index], value, f'{path}[{index}]')
    elif isinstance(expected, (int, float)) and not isinstance(expected, bool):
        if not np.isclose(actual, expected, rtol=0, atol=PROBABILITY_TOLERANCE):
            raise ValueError(f'{path} differs: {actual} != {expected}.')
    elif actual != expected:
        raise ValueError(f'{path} differs: {actual} != {expected}.')


def audit():
    preregistration = prepare_preregistration()
    capture_baseline_integrity()
    train, validation, test = split(load(SOURCE))
    development = load(OUTPUT / 'development.csv')
    manifests = [completed_candidate(config['name'], preregistration, validation, development)
                 for config in CANDIDATES]
    if any(manifest is None for manifest in manifests):
        raise ValueError('Not all preregistered candidates have valid completed artifacts.')
    for manifest in manifests:
        with np.load(scores_for(manifest['name']), allow_pickle=False) as scores:
            recomputed = candidate_measurements(
                validation, development, scores['validation_probabilities'],
                scores['development_probabilities'])
        assert_mapping_close(recomputed, manifest['measurements'], manifest['name'])
        if manifest['score_dimensions'] != {'validation_probabilities': [300],
                                            'development_probabilities': [5000]}:
            raise ValueError('Cached development score dimensions are incorrect.')
    selection = read_json(SELECTION_PATH)
    if [row['name'] for row in selection['candidates']] != [row['name'] for row in CANDIDATES]:
        raise ValueError('Development selection contains an unregistered candidate list.')
    assert_mapping_close(select_candidate(selection['candidates']),
                         {key: selection[key] for key in ('selected_candidate', 'selected_challenger',
                          'baseline_retained', 'eligible_candidates', 'selection_keys')})
    freeze = load_freeze()
    partitions = {'train': train, 'validation': validation, 'test': test, 'development': development}
    if FINAL_PATH.exists():
        final = load(OUTPUT / freeze['final']['file'])
        partitions['final'] = final
        report = read_json(FINAL_PATH)
        if report['final_dataset_sha256'] != sha256_file(OUTPUT / freeze['final']['file']):
            raise ValueError('Final dataset hash differs from its report.')
        if report['final_scores_sha256'] != sha256_file(OUTPUT / 'final-scores.npz'):
            raise ValueError('Final score archive hash differs from its report.')
        with np.load(OUTPUT / 'final-scores.npz', allow_pickle=False) as scores:
            expected_names = [CONTROL] if freeze['baseline_retained'] else [CONTROL, freeze['selected_candidate']]
            expected_arrays = {f'{name}_probabilities' for name in expected_names} | {'final_labels', 'final_ids'}
            if set(scores.files) != expected_arrays:
                raise ValueError('Final evaluation contains arrays for nonselected candidates.')
            if not np.array_equal(scores['final_labels'], final.at_risk.to_numpy()):
                raise ValueError('Final labels differ from the final cohort.')
            if not np.array_equal(scores['final_ids'].astype(str), final.student_id.to_numpy(dtype=str)):
                raise ValueError('Final IDs differ from the final cohort.')
            for name in expected_names:
                score = scores[f'{name}_probabilities']
                if score.shape != (FINAL_COUNT,) or not np.isfinite(score).all():
                    raise ValueError(f'Invalid final scores for {name}.')
                cutoff = read_json(manifest_for(name))['measurements']['validation']['operating_point']['threshold']
                recomputed = {'validation_operating_point': read_json(manifest_for(name))['measurements']['validation']['operating_point'],
                              'fixed_cutoff': metrics(final.at_risk, score, cutoff),
                              'matched_recall': recall_operating_point(final.at_risk, score)}
                cached = {key: report['results'][name][key] for key in recomputed}
                assert_mapping_close(recomputed, cached, f'final.{name}')
    names = list(partitions)
    for index, left in enumerate(names):
        for right in names[index + 1:]:
            overlap = set(partitions[left].student_id) & set(partitions[right].student_id)
            if overlap:
                raise ValueError(f'Student overlap between {left} and {right}: {len(overlap)}.')
    value = {'status': 'passed', 'candidates_checked': len(manifests),
             'protected_artifacts_checked': len(read_json(OUTPUT / 'baseline-integrity.json')['artifacts']),
             'partitions_disjoint': names, 'final_evaluated': FINAL_PATH.exists(),
             'final_scores_checked': FINAL_PATH.exists()}
    write_json(OUTPUT / 'audit-report.json', value)
    print(json.dumps(value, indent=2), flush=True)
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('phase', choices=('sweep', 'final', 'audit'))
    args = parser.parse_args()
    if args.phase == 'sweep':
        sweep()
    elif args.phase == 'final':
        final_evaluation()
    else:
        audit()


if __name__ == '__main__':
    main()
